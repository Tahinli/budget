pub fn kind_label(lang: Lang, kind: TxnKind) -> &'static str {
    match kind {
        TxnKind::Pos => t(lang, Key::KindPos),
        TxnKind::Installment => t(lang, Key::KindInstallment),
        TxnKind::Payment => t(lang, Key::KindPayment),
        TxnKind::Refund => t(lang, Key::KindRefund),
    }
}

pub fn category_label(lang: Lang, id: &str, stored: &str) -> String {
    let key = match id {
        "01CATMARKET000000000000000" => Key::CatMarket,
        "01CATYEME00000000000000000" => Key::CatFood,
        "01CATULASIM000000000000000" => Key::CatTransport,
        "01CATFATURA00000000000000" => Key::CatBills,
        "01CATSAGLIK00000000000000" => Key::CatHealth,
        "01CATGIYIM000000000000000" => Key::CatClothes,
        "01CATTEKNO000000000000000" => Key::CatTech,
        "01CATEGITIM00000000000000" => Key::CatEducation,
        "01CATEGLENCE0000000000000" => Key::CatFun,
        "01CATABONE000000000000000" => Key::CatSub,
        "01CATKONUT000000000000000" => Key::CatHome,
        "01CATDIGER000000000000000" => Key::CatOther,
        "01CATIADE0000000000000000" => Key::CatRefund,
        "01CATODEME000000000000000" => Key::CatCardPay,
        _ => return stored.to_string(),
    };
    t(lang, key).to_string()
}

/// Fill `{}` once. Used for the handful of keys that carry a number.
pub fn tf(lang: Lang, key: Key, a: &str) -> String {
    t(lang, key).replacen("{}", a, 1)
}
